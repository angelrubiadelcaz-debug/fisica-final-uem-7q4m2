let nextIndex = 1;

function clean(text = "") {
  return String(text).replace(/\s+/g, " ").trim();
}

function placeOptions(correct, distractors) {
  const target = (nextIndex - 1) % 4;
  const values = [correct, ...distractors].map(clean);
  const unique = [];
  values.forEach((value) => {
    if (value && !unique.includes(value)) unique.push(value);
  });
  while (unique.length < 4) unique.push("No se puede determinar con los datos dados.");

  const [right, ...wrong] = unique.slice(0, 4);
  const opciones = [];
  let wrongIndex = 0;
  for (let index = 0; index < 4; index += 1) {
    opciones[index] = index === target ? right : wrong[wrongIndex++];
  }
  return { opciones, correcta: target };
}

function g({
  tema,
  subtema,
  dificultad = "media",
  enunciado,
  correct,
  distractors,
  explicacion,
  teoria,
  formula = "",
}) {
  const index = nextIndex;
  const { opciones, correcta } = placeOptions(correct, distractors);
  nextIndex += 1;
  return {
    id: `guia-final-${String(index).padStart(3, "0")}`,
    tema,
    subtema,
    dificultad,
    tipo: "guia final",
    enunciado,
    opciones,
    correcta,
    explicacion,
    teoria,
    formula,
    source,
    prioridad: "maxima",
    etiqueta: "Guia final PDF",
    tags: ["guia-final", "importante", "examen-seguro"],
  };
}

