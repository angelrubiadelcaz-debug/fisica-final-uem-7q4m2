function seguroQuestion({
  id,
  tema,
  subtema,
  titulo,
  dificultad = "media",
  enunciado,
  opciones,
  respuesta,
  solucion,
  explicacion,
  trampa,
  formula = "",
  sourceLabel,
  tags = [],
}) {
  const correcta = typeof respuesta === "number" ? respuesta : letterToIndex[respuesta];

  return {
    id,
    tema,
    subtema,
    titulo,
    dificultad,
    tipo: "seguro examen",
    enunciado,
    opciones,
    correcta,
    respuestaCorrecta: typeof respuesta === "string" ? respuesta : String.fromCharCode(65 + respuesta),
    correctAnswer: correcta,
    solucion,
    solucionPasoAPaso: solucion,
    explicacion,
    explicacionBreve: explicacion,
    trampaTipica: trampa,
    teoria:
      "Pregunta de repaso prioritario. Identifica primero el concepto fisico, las magnitudes implicadas y la trampa de unidades, signos o interpretacion antes de calcular.",
    formula,
    seguroExamen: true,
    importante: true,
    importancia: "Seguro examen",
    etiqueta: "Muy importante",
    source: "Preguntas seguro examen",
    sourceLabel,
    statementCard: {
      label: "Enunciado seguro examen",
    },
    tags: ["seguro-examen", "muy-importante", ...tags],
  };
}

