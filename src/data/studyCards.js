function normalize(value) {
  return String(value || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
}

function relatedQuestionIdsFor(card) {
  const terms = [
    card.titulo,
    card.subtema,
    ...(card.etiquetas || []),
    ...(card.relatedTerms || []),
  ]
    .map(normalize)
    .filter((term) => term.length > 2);

  const scored = questions
    .map((question) => {
      const haystack = normalize(
        [
          question.tema,
          question.subtema,
          question.enunciado,
          question.explicacion,
          question.teoria,
          question.formula,
          question.tipo,
        ].join(" "),
      );
      const subtopic = normalize(question.subtema);
      let score = card.temaBanco && question.tema.startsWith(card.temaBanco) ? 1 : 0;
      terms.forEach((term) => {
        if (subtopic === term || subtopic.includes(term) || term.includes(subtopic)) score += 5;
        else if (haystack.includes(term)) score += 2;
      });
      return { question, score };
    })
    .filter((item) => item.score > 2)
    .sort((a, b) => b.score - a.score || a.question.id - b.question.id)
    .slice(0, 12)
    .map((item) => item.question.id);

  if (scored.length) return scored;
  return questions
    .filter((question) => card.temaBanco && question.tema.startsWith(card.temaBanco))
    .slice(0, 8)
    .map((question) => question.id);
}

